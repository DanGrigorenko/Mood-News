import { z } from 'zod'

// Набор Mood конечен и задан кодом — пользователь не может придумать свой
// (см. CONTEXT.md). Порядок здесь — порядок, в котором Mood показываются фронту.
export const MOOD_IDS = ['neutral', 'joyful', 'sad', 'ironic', 'dramatic'] as const

export const moodSchema = z.enum(MOOD_IDS)
export type Mood = z.infer<typeof moodSchema>

// Человеческие названия Mood: их отдаёт GET /api/moods, чтобы фронт не дублировал
// список у себя.
export const MOOD_LABELS: Record<Mood, string> = {
  neutral: 'Нейтрально',
  joyful: 'Радостно',
  sad: 'Грустно',
  ironic: 'Иронично',
  dramatic: 'Драматично',
}

// Регистр — позиция рассказчика, а не переоценка события (см. CONTEXT.md,
// docs/adr/0007). Каждый Mood описывает, ЧЕЙ это голос и что этот голос делает с
// плохой новостью: радость не отрицает беду, ирония не целится в пострадавших.
// Меняется тон подачи, исход события (Outcome) остаётся неизменным.
export const MOOD_REGISTER: Record<Mood, string> = {
  neutral:
    'Позиция бесстрастного репортёра. Сухо и сжато пересказывает событие своими словами, без эмоций и оценок. Это не побуквенная копия источника, а его сжатый пересказ.',
  joyful:
    'Позиция рассказчика, который ищет в событии надежду и то, что будет дальше. На плохой новости он не отрицает беду и не радуется ей — он находит, за что можно держаться, и куда двигаться. Радость — это его взгляд, а не оценка события.',
  sad: 'Позиция рассказчика, который проживает событие с печалью и сочувствием. На плохой новости он грустит соразмерно произошедшему, не нагнетая сверх того, что случилось.',
  ironic:
    'Позиция рассказчика с иронией и лёгкой насмешкой. Насмешка целится в обстоятельства, нелепость и виновных — но никогда в пострадавших. Над бедой людей он не глумится.',
  dramatic:
    'Позиция рассказчика, поднимающего ставки самими формулировками. Драма держится на реальном событии: он усиливает подачу, но не выдумывает последствий, которых в источнике нет.',
}

// Список Mood с человеческими названиями для GET /api/moods.
export function moodsPayload(): { moods: Array<{ id: Mood; label: string }> } {
  return {
    moods: MOOD_IDS.map((id) => ({ id, label: MOOD_LABELS[id] })),
  }
}
