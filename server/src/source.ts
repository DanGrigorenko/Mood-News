// Source — внешняя лента, из которой приходят Article. Набор Source конечен и
// задан проектом (как MOOD_IDS в общем контракте): пользователь не заводит свой.
// Раньше Source был голой строкой по обе стороны seam Ingest — список лент нёс
// source: string, а таблица правил извлечения индексировалась тем же значением
// как произвольной строкой. Ключи кириллические, с пробелом («РИА Новости») и с
// твёрдым знаком («Коммерсантъ»); разойдись они — правило не находилось, текст
// «пропадал», лента гасла молча. Теперь id — конечный набор, тип выведен из него,
// а url ленты и правило извлечения на один Source живут рядом (см. SOURCES):
// расхождение ключей — ошибка компиляции, а не погасшая лента.
//
// Список сокращён до источников, чьи страницы открыты. ТАСС (JS-капча
// Servicepipe) и Lenta.ru (редирект на заглушку) убраны — их страницы закрыты.

export const SOURCE_IDS = ['Коммерсантъ', 'РИА Новости', 'Интерфакс'] as const
export type Source = (typeof SOURCE_IDS)[number]

// Сужение произвольной строки до Source: чужой источник (или опечатка на входе
// извне набора) — не Source, извлечение по нему вернёт null, а не бросит.
export function isSource(value: string): value is Source {
  return (SOURCE_IDS as readonly string[]).includes(value)
}

// Правило извлечения полного текста со страницы публикации. Универсального
// разбора не существует: общий проход по абзацам тащит рекламу, меню и навигацию
// (проверено). Поэтому по одному узкому правилу на источник — адресный контейнер
// конкретной вёрстки, а не «весь текст страницы».
export type ExtractionRule = {
  // region (необязателен): сначала сузить HTML до одного контейнера с телом
  // статьи, чтобы блоки за его пределами не попадали в текст. Группа 1 — тело.
  region?: RegExp
  // block: как выглядит один текстовый блок внутри тела. Глобальный флаг, группа
  // 1 — внутренний HTML блока (теги снимаются отдельно).
  block: RegExp
}

// Url ленты и правило извлечения на один Source — рядом, в одной записи. Завести
// новый источник — одна правка здесь. Таблица индексируется Source: пропусти
// ключ или опечатайся — ошибка компиляции (Record<Source, …>), а не молчание.
//
// Проверено 2026-08-16 (см. ADR, пересматривающий 0004):
//   Коммерсантъ — абзацы <p class="doc__text">
//   РИА Новости — блоки <div class="article__text">
//   Интерфакс   — абзацы <p> внутри <article itemprop="articleBody">
export const SOURCES: Record<Source, { url: string; rule: ExtractionRule }> = {
  Коммерсантъ: {
    url: 'https://www.kommersant.ru/RSS/news.xml',
    rule: {
      block: /<p[^>]*class="[^"]*\bdoc__text\b[^"]*"[^>]*>([\s\S]*?)<\/p>/g,
    },
  },
  'РИА Новости': {
    url: 'https://ria.ru/export/rss2/archive/index.xml',
    rule: {
      block: /<div[^>]*class="[^"]*\barticle__text\b[^"]*"[^>]*>([\s\S]*?)<\/div>/g,
    },
  },
  Интерфакс: {
    url: 'https://www.interfax.ru/rss.asp',
    rule: {
      region: /<article[^>]*itemprop="articleBody"[^>]*>([\s\S]*?)<\/article>/,
      block: /<p[^>]*>([\s\S]*?)<\/p>/g,
    },
  },
}
